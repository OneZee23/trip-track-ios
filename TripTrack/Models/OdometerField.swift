import Foundation

/// Поле ручного пробега: разбор того, что человек списал с приборной панели, и
/// печать того, что в нём стоит.
///
/// **Единственный вход, где ошибка с единицей попадает в БАЗУ.** Всё остальное
/// в 0.6.7 — показ: напечатали не то, поправили, перепечатали. Здесь число
/// уезжает в `VehicleEntity.manualOdometerKm`, оттуда на сервер и на второй
/// телефон, и разобранное не в той единице оно уже неотличимо от настоящего:
/// экран при открытии переведёт его обратно тем же коэффициентом и покажет
/// ровно то, что набрали. Приложение ни разу себе не противоречит — заметить
/// нечем, вылезет через полгода как восемьдесят шесть тысяч фантомных
/// «недотреканных» километров.
///
/// **Единица — МАШИНЫ, а не человека** (`Vehicle.dashboardUnit(app:)`).
/// Вопрос, на который отвечает это поле, один: «что написано на панели». У
/// американца с тойотой там километры, у русского с мустангом — мили, и
/// глобальная настройка приложения не знает про это ничего.
///
/// **Функцией, а не методом экрана.** Правило обязан держать тест, а не
/// открытая форма на телефоне: разбор, живущий внутри `body`, проверяется
/// только руками и только тем, кто помнит, что его надо проверить. Ровно эта
/// причина записана в CLAUDE.md про `AutoTripPolicy` и `JourneyEditSheet`.
enum OdometerField {

    /// То, что напечатано в поле, → километры для ХРАНЕНИЯ.
    ///
    /// `nil` — «не вводили», и это не то же самое, что ноль: ноль стёр бы
    /// разрыв «недотрекано» у человека, который просто очистил строку, чтобы
    /// перенабрать. Поэтому опционал идёт до самого `setManualOdometer`, где
    /// `nil` означает «вернуть карточку к треканному числу».
    ///
    /// Хранение метрическое ВСЕГДА: `Vehicle.odometerKm` — километры при любой
    /// приборке, потому что против него уже записаны уровни машин в базе.
    static func storedKm(_ text: String, unit: DistanceUnit) -> Double? {
        let trimmed = text.trimmingCharacters(in: .whitespaces)
        guard !trimmed.isEmpty, let shown = Double(trimmed) else { return nil }
        return unit.metres(fromDistance: shown) / 1000
    }

    /// Километры из базы → то, что стоит в поле. Целое: поле принимает только
    /// ASCII-цифры (клавиатура `.numberPad`), и десятая доля мили в нём не
    /// набирается и не нужна — пробег с панели списывают целыми.
    ///
    /// Круг «база → поле → база» из-за этого не сходится ПОБИТОВО у миль:
    /// 100 000 км показываются как 62 137 миль, а 62 137 миль — это 100 000,3
    /// км. Поэтому форма решает «менялось ли» сравнением СТРОК, а не
    /// километров: сравнение чисел объявляло бы пробег изменившимся при каждом
    /// сохранении и ставило бы лишнюю операцию в очередь синка.
    static func fieldText(km: Double?, unit: DistanceUnit) -> String {
        guard let km else { return "" }
        return String(Int(unit.distance(fromMetres: km * 1000).rounded()))
    }
}
