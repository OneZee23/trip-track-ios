import Foundation

/// Как ехал плагин-гибрид в ЭТОЙ поездке.
///
/// Считает по-прежнему приложение (`EnergyEstimate`, запас хода на день);
/// человек поправляет одним нажатием там, где знает лучше. Вопроса после
/// поездки нет нигде и не будет — это плата вниманием за каждую поездку, а
/// правка на экране отвечает на тот же вопрос, но только когда человеку есть
/// что поправить (решение владельца 25 сентября 2026).
///
/// **`rawValue` менять нельзя никогда** — это колонка `TripEntity.energyMode`
/// и поле `TripSyncPayload.energyMode`.
///
/// **`auto` — значение, а не отсутствие значения.** В базе оно лежит как
/// `nil` (экономия на миллионе поездок, у которых выбора не было), но НА
/// ПРОВОДЕ оно едет строкой, и это не мелочь: если бы «Авто» уезжало
/// отсутствием ключа, оно стало бы неотличимо от «старый клиент молчит», и
/// возврат с «Электро» обратно на «Авто» не доехал бы до второго телефона
/// никогда. Дисциплина ключа та же, что у `checkpoints` и `segments`: ключа
/// нет — не трогаем локальное; ключ есть — он и есть ответ.
enum TripEnergyMode: String, Codable, CaseIterable {
    /// Считает приложение: первые километры дня с ночного заряда.
    case auto
    /// Вся поездка на электричестве, даже если она длиннее запаса. Человек
    /// знает лучше: настоящий запас гуляет с погодой и сезоном.
    case electric
    /// Вся поездка на топливе.
    case fuel

    /// Терпимый разбор — ровно как у `TripOrigin`, и по той же причине.
    ///
    /// `TripSyncPayload` кодируется синтезированным `Codable`, а тот на
    /// незнакомой строке БРОСАЕТ — то есть роняет пейлоад поездки целиком
    /// из-за одного поля, которое приедет с первого же клиента, знающего
    /// четвёртый режим. Пустая строка, будущее значение и отсутствие ключа
    /// здесь одинаково значат «считает приложение».
    init(from decoder: Decoder) throws {
        let raw = try decoder.singleValueContainer().decode(String.self)
        self = TripEnergyMode(rawValue: raw) ?? .auto
    }

    /// Разбор того, что приехало из базы или с сервера.
    ///
    /// `nil` на входе — это поездка, записанная до 0.8.3, и её ответ «Авто».
    /// Незнакомое слово с будущего клиента — тоже: подставлять вместо него
    /// «Топливо» значило бы молча переписать человеку раскладку.
    static func parse(_ raw: String?) -> TripEnergyMode {
        guard let raw, let mode = TripEnergyMode(rawValue: raw) else { return .auto }
        return mode
    }

    /// Что писать в колонку базы. «Авто» — это `nil`: у поездки, где выбора не
    /// делали, хранить нечего.
    var stored: String? { self == .auto ? nil : rawValue }
}
