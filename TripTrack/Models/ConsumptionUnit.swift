import Foundation

/// В чём показывают расход ЭТОЙ машины: литры на сотню километров или мили на
/// галлон.
///
/// Не переименование друг друга — они идут в РАЗНЫЕ стороны. 6 л/100 км —
/// экономичная машина, 6 mpg — грузовик с проблемой. Прошлая версия экрана
/// подписала хранимые километровые числа словом «mpg», ничего не переведя, и
/// уехала карточка, хвалящая прожорливость; поэтому конверсия живёт здесь, в
/// одном месте и под тестами, а не у каждой точки вызова.
///
/// **Хранение не меняется никогда.** `Vehicle.cityConsumption` и
/// `.highwayConsumption` — всегда литры на сотню КИЛОМЕТРОВ, `fuelPrice` —
/// всегда за литр. Этот тип решает только, что человек видит и как
/// возвращается то, что он набрал.
///
/// **Диалект ВЫВОДИТСЯ из приборки машины, а не настраивается отдельно**
/// (`forDashboard`). Отдельной галочкой он давал четыре комбинации вместо
/// двух, и лишние две — ложь: «литры на сотню МИЛЬ» — единица, в которой не
/// ездит никто, зато число в ней молча другое (сотня миль длиннее сотни
/// километров в 1.609344 раза, и литров на неё уходит во столько же больше).
/// Своей галочки у расхода больше нет, и комбинация не выражается: `per100`
/// означает сотню километров и ничего кроме.
///
/// **Глобального умолчания у типа нет — ни ключа, ни `current`.** Было, и
/// через него шёл живой баг обеими половинами: экран поездки печатал объём по
/// настройке аккаунта мимо машины (поездка на тойоте выходила в галлонах,
/// если в гараже стояла американка), а сегмент на карточке КОНКРЕТНОЙ машины
/// писал в ту же настройку — и она уезжала на сервер, переводя в галлоны весь
/// аккаунт. Машин в гараже несколько, настройка одна; спрашивать её про расход
/// нечего. Держит `VehicleConsumptionUnitTests`.
///
/// **Галлон американский ВЕЗДЕ.** Имперский (4.546 л) молча разошёлся бы с
/// полем цены строкой ниже: одно и то же слово значило бы в расходе одно, а в
/// цене другое. Поэтому британского микса (мили + литры + imperial mpg) в
/// 0.6.7 нет, и это решение, а не недоделка.
enum ConsumptionUnit: String, CaseIterable {
    /// Литры на сотню КИЛОМЕТРОВ — ровно то, в чём расход хранится.
    case per100
    /// Мили на американский галлон.
    case mpg

    /// Единственная дверь внутрь типа: диалект — следствие приборки.
    ///
    /// Второй такой `switch` где-нибудь в экране — это место, где однажды
    /// напишут «мили и литры».
    static func forDashboard(_ unit: DistanceUnit) -> ConsumptionUnit {
        switch unit {
        case .km: return .per100
        case .miles: return .mpg
        }
    }

    /// US gallons: 100 × 3.785411784 L/gal ÷ 1.609344 km/mi.
    ///
    /// Имперская константа — 282.48, и стой она здесь, mpg и цена считали бы
    /// разные галлоны.
    static let mpgConstant: Double = 235.214583

    static let litresPerGallon: Double = 3.785411784

    /// Хранимое значение → то, что показать.
    func display(fromPer100 value: Double) -> Double {
        switch self {
        case .per100:
            return value
        case .mpg:
            // У машины, которая не жжёт ничего, нет mpg — ноль на входе, ноль
            // на выходе, а не бесконечность, которая печатается как «inf».
            guard value > 0 else { return 0 }
            return Self.mpgConstant / value
        }
    }

    /// То, что человек набрал, → то, что хранить. Всегда литры на сотню км.
    func toPer100(_ displayed: Double) -> Double {
        switch self {
        case .per100:
            return displayed
        case .mpg:
            guard displayed > 0 else { return 0 }
            return Self.mpgConstant / displayed
        }
    }

    /// Потолок поля ввода — В ЕДИНИЦАХ ПОКАЗА. 50 л/100 км — абсурдная машина,
    /// 50 mpg — обычная, и общее число отвергло бы у мильного человека вполне
    /// нормальный расход.
    var inputCeiling: Double {
        self == .mpg ? 250 : 50
    }

    /// Подпись у числа.
    ///
    /// У `per100` она собирается, потому что склоняется сотня («л/100 км»); у
    /// mpg слово одно на все тринадцать языков — это символ, а не
    /// существительное.
    func valueUnit(_ lng: LanguageManager.Language) -> String {
        switch self {
        case .per100: return GarageFormat.consumptionUnit(lng: lng)
        case .mpg:    return "mpg"
        }
    }

    // MARK: - Топливо

    /// Мильная приборка — это галлоны. «Мили на галлон» и «рубли за литр» не
    /// набор единиц, которым кто-то пользуется, поэтому объём едет за
    /// диалектом, а строка цены — за объёмом.
    var volumeUnit: VolumeUnit {
        self == .mpg ? .gallons : .liters
    }

    /// `Vehicle.fuelPrice` хранится ЗА ЛИТР — на это число умножаются литры
    /// поездки. Настройка галлонов когда-то меняла только подпись у поля, и
    /// «65 ₽/л» становились «65 ₽/gal» одним нажатием, а каждая поездка молча
    /// оставалась посчитанной по литровой цене.
    func displayPrice(fromPerLitre value: Double) -> Double {
        self == .mpg ? value * Self.litresPerGallon : value
    }

    func priceToPerLitre(_ displayed: Double) -> Double {
        self == .mpg ? displayed / Self.litresPerGallon : displayed
    }
}
