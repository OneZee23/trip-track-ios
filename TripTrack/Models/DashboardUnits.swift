import Foundation

/// В чём показывает приборка ЭТОЙ машины — и только она.
///
/// Вопрос, на который отвечает тип, один: «если человек сейчас глянет на
/// панель, он увидит ровно это число?». Да — единица машины, нет — единица
/// человека (`DistanceUnit`). Американец с тойотой, у которой на панели
/// километры, и русский с американкой, у которой мили, — это один и тот же
/// человек с одной настройкой приложения и разными машинами, и никакая
/// догадка по региону их не различит.
///
/// **Что этот тип НЕ имеет права трогать.** Хранение и награды. `Trip.distance`
/// — метры, `Vehicle.odometerKm` — километры, расход — литры на сотню
/// километров, цена — за литр, `scoringKm`, опыт, уровень машины и пороги
/// значков — метрические при любой настройке. Единица приборки живёт строго на
/// границе ПОКАЗА и РАЗБОРА: переводит число прямо перед печатью и переводит
/// обратно то, что человек списал с панели. Опыт и уровень лежат в базе, и
/// сдвинутые конверсией цифры не чинит следующий релиз — откатывать нечего.
/// Держат это `ScoringStaysMetricTests` и `VehicleUnitsStayOutOfRewardsTests`.
///
/// **И не имеет права уходить за пределы паспорта своей машины.** Сумма по
/// нескольким машинам — всегда единица приложения: у суммы миль и километров
/// единицы не существует, а правило «взять у первой» человек не угадает
/// никогда. Ни одна функция, куда приходит больше одной машины, эту настройку
/// не спрашивает.
///
/// **Три значения, а не два, и `app` — не «не задано».** Двузначный выбор
/// (километры или мили) потребовал бы выбрать умолчание для УЖЕ заведённых
/// машин, а любой выбор молча переставил бы цифры у половины людей: у машины,
/// заведённой до 0.6.7, ответа на вопрос «что у неё на панели» просто нет.
/// `app` — честный ответ «показывать как везде в приложении», и это ровно то,
/// что со всеми существующими машинами происходит сегодня. Поэтому миграция
/// физически не может никому сменить показания.
///
/// **`rawValue` менять нельзя.** Ровно эти строки лежат в колонке
/// `VehicleEntity.dashboardUnits`, в поле `VehicleSyncPayload.dashboardUnits`
/// и в колонке `vehicle.dashboard_units` на сервере — то есть это контракт со
/// вторым телефоном.
/// `Codable` — ради `Vehicle`, который целиком `Codable` (кэш ответов и JSON
/// API). На ПРОВОДЕ синка этим синтезом никто не пользуется: там значение
/// разбирается строкой через `parse`, потому что синтезированный разбор на
/// незнакомом значении БРОСАЕТ — то есть роняет машину целиком из-за одного
/// поля, которого этот бинарник ещё не знает.
enum DashboardUnits: String, CaseIterable, Codable {
    /// Как в приложении. Умолчание у новой машины и у всех существующих.
    case app
    /// Километры и литры.
    case metric
    /// Мили и галлоны.
    case imperial

    /// Прочитать сохранённое значение. `nil` — «не знаю такого», и это НЕ
    /// ошибка и НЕ повод подставить `app`.
    ///
    /// Читается вызывающим как «мнения нет, локальное не трогаю» — ровно так
    /// же, как `VehiclesService.normalizeDashboardUnits` читает неизвестное
    /// значение на сервере. Причина та же и она принципиальная: у машины
    /// может лежать осознанное `metric`, и «починка» на `app` перевела бы
    /// километровую панель в единицы приложения молча — то есть сделала бы
    /// ровно ту поломку, ради которой поле заведено. Через эту же дверь
    /// проходит будущая четвёртая единица (британский микс: мили, литры,
    /// imperial mpg) — как «клиент про такое поле не знает», а не как отказ
    /// применить машину целиком.
    static func parse(_ raw: String?) -> DashboardUnits? {
        guard let raw else { return nil }
        return DashboardUnits(rawValue: raw.trimmingCharacters(in: .whitespaces).lowercased())
    }

    /// В чём печатать и разбирать числа ЭТОЙ машины, зная единицу человека.
    ///
    /// Единственное место, где выбор превращается в `DistanceUnit`. Вторая
    /// копия этого `switch` где-нибудь в экране — это место, где однажды
    /// забудут про `app`.
    func resolved(app appUnit: DistanceUnit) -> DistanceUnit {
        switch self {
        case .app: return appUnit
        case .metric: return .km
        case .imperial: return .miles
        }
    }
}

// MARK: - Слова

/// Как выбор называется НА ЭКРАНЕ.
///
/// Здесь, а не в форме паспорта: имя варианта нужно в двух местах сразу —
/// в списке выбора и в живой подсказке под полем ручного пробега, — и
/// разъехаться этим двум написаниям нельзя. Разъехавшись, они задали бы
/// человеку вопрос «это одна настройка или две?» ровно там, где вся версия
/// отвечает «единица — это ответ на вопрос, откуда взято число».
extension DashboardUnits {

    /// Имя варианта в списке.
    ///
    /// **У велосипеда бака нет**, и «Километры и литры» на его экране — слово
    /// про то, чего у этой машины не бывает: топливных карточек в форме у него
    /// тоже нет, они спрятаны по `VehicleType.burnsFuel`. Поэтому там остаётся
    /// одно расстояние — то же самое слово, которым подписан выбор единиц
    /// приложения (`DistanceUnit.labelFull`), и новых строк на это не заведено.
    ///
    /// Объём назван вместе с расстоянием, а не отдельной строкой, потому что
    /// выбор ОДИН и командует обоими: диалект расхода выводится из приборки и
    /// собственной галочки не имеет (см. `ConsumptionUnit.forDashboard`).
    /// Назвать в списке только километры, а поменять заодно и литры — это и
    /// есть «экран обещает одно, а делает другое».
    func label(_ lang: LanguageManager.Language, burnsFuel: Bool) -> String {
        switch self {
        case .app:
            return AppStrings.dashboardUnitsApp(lang)
        case .metric:
            return burnsFuel
                ? AppStrings.dashboardUnitsMetricFuel(lang)
                : DistanceUnit.km.labelFull(lang)
        case .imperial:
            return burnsFuel
                ? AppStrings.dashboardUnitsImperialFuel(lang)
                : DistanceUnit.miles.labelFull(lang)
        }
    }

    /// Имя того, что человек УВИДИТ, — «Как в приложении» из него не выходит
    /// никогда.
    ///
    /// Подсказка под полем ввода отвечает на вопрос «мили или километры я
    /// сейчас набираю», и «как в приложении» на него не отвечает: это ответ на
    /// другой вопрос — чей это выбор. Поэтому `app` здесь разворачивается в ту
    /// единицу, в которую он разрешился.
    func resolvedLabel(
        _ lang: LanguageManager.Language,
        app appUnit: DistanceUnit,
        burnsFuel: Bool
    ) -> String {
        let concrete: DashboardUnits = resolved(app: appUnit) == .miles ? .imperial : .metric
        return concrete.label(lang, burnsFuel: burnsFuel)
    }

    /// Значок в кружке 32pt слева от имени.
    ///
    /// Показывает РАЗРЕШЁННУЮ единицу, поэтому у «Как в приложении» значок тот
    /// же, что у одного из двух других вариантов, — и это не ошибка, а ответ
    /// на «а что у меня сейчас в приложении?», заданный молча и прочитанный
    /// глазами. Выбирают всё равно по имени: три имени различны всегда.
    func badge(_ lang: LanguageManager.Language, app appUnit: DistanceUnit) -> String {
        AppStrings.unitDistanceBadge(lang, unit: resolved(app: appUnit))
    }
}
