import Foundation

/// Как эта поездка появилась в базе — записана треком или вписана рукой
/// (0.8.0, «Плюс»).
///
/// Имя `TripOrigin`, а не `TripSource`: `Services/TripSource.swift` уже
/// занимает это имя протоколом «откуда берётся список поездок для экрана»
/// (свои / чужие / машины) — понятие из другой оси и без единой связи с этой.
/// Совпадение имён скомпилировать нельзя, а название по смыслу здесь и так
/// точнее: «origin» — про то, как поездка возникла, «source» у соседнего типа
/// — про то, откуда её сейчас читают.
///
/// Хранится в `Trip.source` (колонка `TripEntity.source`, поле
/// `TripSyncPayload.source`) — имя ПОЛЯ совпадает с текстом спеки и с
/// колонкой на сервере (`trip.source`), совпадать с именем типа оно не
/// обязано.
///
/// **Ручная поездка не даёт наград.** `.manual` — «Откуда → куда по дорогам»
/// (`MKDirections`, точки с синтетическим временем): км входят в статистику,
/// регионы, атлас и одометр машины, но НЕ в опыт, уровни, значки и находки.
/// Ровно тем же приёмом, что `DashboardUnits`, разбор терпимый: незнакомая
/// строка — это `.recorded`, а не ошибка, потому что второй бинарник узнает
/// третий источник раньше, чем этот прочитает про него.
enum TripOrigin: String, CaseIterable, Codable {
    /// Записана треком GPS — то, чем были все поездки до 0.8.0.
    case recorded
    /// Вписана рукой — маршрут по дорогам между точками, без GPS.
    case manual

    /// Терпимый разбор: пустая строка, будущее значение или отсутствие ключа
    /// — всё это «как записывали раньше», а не повод уронить поездку целиком.
    init(from decoder: Decoder) throws {
        let raw = try decoder.singleValueContainer().decode(String.self)
        self = TripOrigin(rawValue: raw) ?? .recorded
    }
}
