import CoreLocation
import Foundation

/// Обрезка трека внутри приватной зоны у дома (0.8.2).
///
/// **Режется то, что УХОДИТ С ТЕЛЕФОНА, а не то, что показывается.** Своя
/// поездка на своём телефоне остаётся целой всегда — это история человека, и
/// прятать её от него самого не от кого. Обрезка живёт на ОДНОЙ границе, в
/// сборке пейлоада синка: обрежь на показе — и полный трек всё равно уже
/// лежит на сервере и в чужой ленте.
///
/// Чистыми функциями, потому что проверить это можно только счётом: «точка в
/// 199 м от дома не уехала, точка в 201 м уехала» не выражается ни состоянием
/// экрана, ни возвращаемым значением сервиса.
enum PrivacyZone {

    /// Точка внутри зоны — значит, она с телефона не уезжает.
    ///
    /// Строго меньше радиуса: ровно на границе точка остаётся. Граница —
    /// это уже «не дома», и круг на карте рисуется по тому же числу.
    static func hides(_ coordinate: CLLocationCoordinate2D,
                      centre: CLLocationCoordinate2D, radius: Double) -> Bool {
        GeometryUtils.haversineDistance(coordinate, centre) < radius
    }

    /// Убрать из трека всё, что внутри зоны.
    ///
    /// Вырезается ВЕЗДЕ, а не только у концов: домой заезжают и посреди
    /// поездки, и «обрезать только начало и конец» оставило бы двор на карте
    /// у того, кто в обед заехал переодеться.
    ///
    /// Разрыв в оставшемся треке — это не поломка, а ответ: публичный трек
    /// начинается от края зоны. Достройка дыр (`RoadGapFiller`) сюда не
    /// ходит: она работает на СВОЁМ треке в базе, а не на пейлоаде.
    static func trim(points: [TrackPoint],
                     centre: CLLocationCoordinate2D, radius: Double) -> [TrackPoint] {
        points.filter { !hides($0.coordinate, centre: centre, radius: radius) }
    }

    /// То же для превью: его рисует карточка в чужой ленте, и необрезанное
    /// превью выдало бы двор даже при обрезанном треке.
    static func trim(coordinates: [CLLocationCoordinate2D],
                     centre: CLLocationCoordinate2D, radius: Double) -> [CLLocationCoordinate2D] {
        coordinates.filter { !hides($0, centre: centre, radius: radius) }
    }

    /// Осталось ли от трека хоть что-то, что можно нарисовать.
    ///
    /// Поездка целиком внутри зоны (круг по своему кварталу) уезжает БЕЗ
    /// трека вовсе, и это честно: она вся произошла там, куда человек никого
    /// не пускает. Карточка в ленте покажет её без маршрута, а не с куском.
    static func isDrawable(_ count: Int) -> Bool { count >= 2 }
}
