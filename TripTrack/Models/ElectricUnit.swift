import Foundation

/// В чём показывают расход электричества ЭТОЙ машины: киловатт-часы на сотню
/// километров или мили на киловатт-час.
///
/// Близнец `ConsumptionUnit`, и близнец намеренный: у топлива та же пара
/// «сколько тратим на расстояние» ↔ «сколько проезжаем на единице», и они так
/// же идут в РАЗНЫЕ стороны. 16 кВт·ч/100 км — экономичная машина, 16 mi/kWh —
/// число, которого не бывает.
///
/// **Хранение не меняется никогда.** `Vehicle.electricConsumption` — всегда
/// киловатт-часы на сотню КИЛОМЕТРОВ, `electricityPrice` — всегда за киловатт-час.
/// Этот тип решает только, что человек видит и как возвращается то, что он набрал.
///
/// **Диалект ВЫВОДИТСЯ из приборки машины** (`forDashboard`), а не настраивается
/// отдельной галочкой — ровно по той же причине, что у топлива: своя галочка
/// давала бы «киловатт-часы на сотню МИЛЬ», единицу, в которой не ездит никто,
/// зато число в ней молча другое.
///
/// **Цена электричества от диалекта НЕ зависит, и это разница с топливом.**
/// У бензина мильная приборка тянет за собой галлоны, и цена едет за объёмом;
/// киловатт-час же одинаков во всём мире — пересчитывать его не во что. Поэтому
/// пары `displayPrice`/`priceToPerLitre` здесь нет вовсе, а не «есть и
/// возвращает то же самое»: второй такой функции нечего делать в коде.
///
/// **Своей константы миль тут НЕТ.** Перевод идёт через `DistanceUnit`, который
/// и есть единственный держатель 1609.344 (CLAUDE.md, «Честные единицы»).
/// Четвёртая копия этого числа — четвёртое место, где его однажды округлят до
/// 1609.34, и разойдутся тогда не единицы, а деньги.
enum ElectricUnit: String, CaseIterable {
    /// Киловатт-часы на сотню КИЛОМЕТРОВ — ровно то, в чём расход хранится.
    case per100kWh
    /// Мили на киловатт-час.
    case miPerKWh

    /// Единственная дверь внутрь типа: диалект — следствие приборки.
    static func forDashboard(_ unit: DistanceUnit) -> ElectricUnit {
        switch unit {
        case .km: return .per100kWh
        case .miles: return .miPerKWh
        }
    }

    /// Сотня километров в метрах — делимое при переводе в «мили на киловатт-час».
    private static let hundredKilometresInMetres: Double = 100_000

    /// Хранимое значение → то, что показать.
    ///
    /// У машины, которая не тратит ничего, нет и миль на киловатт-час: ноль на
    /// входе — ноль на выходе, а не бесконечность, которая печатается как «inf»
    /// (правило `ConsumptionUnit.display`).
    func display(fromPer100 value: Double) -> Double {
        switch self {
        case .per100kWh:
            return value
        case .miPerKWh:
            guard value > 0 else { return 0 }
            // Сто километров на `value` киловатт-часов — значит на один
            // киловатт-час приходится столько метров; в мили их переводит
            // `DistanceUnit`, и больше никто.
            let metresPerKWh = Self.hundredKilometresInMetres / value
            return DistanceUnit.miles.distance(fromMetres: metresPerKWh)
        }
    }

    /// То, что человек набрал, → то, что хранить. Всегда киловатт-часы на сотню км.
    func toPer100(_ displayed: Double) -> Double {
        switch self {
        case .per100kWh:
            return displayed
        case .miPerKWh:
            guard displayed > 0 else { return 0 }
            let metresPerKWh = DistanceUnit.miles.metres(fromDistance: displayed)
            guard metresPerKWh > 0 else { return 0 }
            return Self.hundredKilometresInMetres / metresPerKWh
        }
    }

    /// Потолок поля ввода — В ЕДИНИЦАХ ПОКАЗА.
    ///
    /// 60 кВт·ч/100 км — электрический грузовик, дальше начинается опечатка;
    /// 12 mi/kWh — рекорд лёгкого прототипа, у серийных машин 2…5. Общее число
    /// отвергло бы у мильного человека вполне нормальный расход — та же
    /// причина, по которой у `ConsumptionUnit` потолки 50 и 250.
    var inputCeiling: Double {
        self == .miPerKWh ? 12 : 60
    }

    /// Подпись у числа.
    ///
    /// У `per100kWh` она СОБИРАЕТСЯ, потому что склоняется сотня километров, а
    /// сам киловатт-час пишется по-разному («кВт·ч», «kWh», «кВт·сағ»); у
    /// `miPerKWh` слово одно на все тринадцать языков — это символ, а не
    /// существительное, и в таблицах переводов ему делать нечего. Ровно так же
    /// разведены «л/100 км» и «mpg» у `ConsumptionUnit`.
    func valueUnit(_ lng: LanguageManager.Language) -> String {
        switch self {
        case .per100kWh: return GarageFormat.electricConsumptionUnit(lng: lng)
        case .miPerKWh:  return "mi/kWh"
        }
    }
}
