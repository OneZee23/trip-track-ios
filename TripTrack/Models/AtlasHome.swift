import CoreLocation
import Foundation

/// Дом на «Атласе»: сколько поездок отсюда (спека v3, состояние 26).
///
/// «61 поездка отсюда» — про СТАРТ, а не про «рядом проезжал»: карточка дома
/// отвечает на «сколько раз я отсюда уезжал», и проезд мимо на это не
/// отвечает. Поэтому считается первая точка превью, а не весь трек.
enum AtlasHome {

    /// Насколько близко к дому должна начаться поездка, чтобы считаться
    /// «отсюда».
    ///
    /// 150 м — размер ячейки geohash-7, которой приложение уже меряет «то же
    /// самое место» (`Place.cell`, 0.6.8). Радиусом, а не ячейкой: у ячейки
    /// есть границы, и двор, попавший на стык, делился бы надвое — а у дома
    /// это видно сразу, он один.
    static let radius: CLLocationDistance = 150

    /// Сколько поездок началось у дома.
    ///
    /// Точки не поднимаются: считаются НАЧАЛА превью — то же правило, что у
    /// подсказок мест и у «Атласа» вообще (у зрелой библиотеки миллионы
    /// точек, и один поход за ними кладёт экран на секунды). Поездка без
    /// превью пропускается целиком.
    static func tripsStarted(at home: CLLocationCoordinate2D,
                             starts: [CLLocationCoordinate2D],
                             radius: CLLocationDistance = radius) -> Int {
        starts.filter { GeometryUtils.haversineDistance($0, home) <= radius }.count
    }
}
