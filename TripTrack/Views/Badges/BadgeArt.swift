import SwiftUI

/// Рисунок значка — пиксельная гравюра из `Assets.xcassets/Badges`.
///
/// **Диск и ободок редкости ВШИТЫ в сам рисунок**, поэтому вокруг него не
/// рисуется ни круга, ни кольца: два диска подряд читались бы значком внутри
/// значка. До 0.8.2 на всех шести местах показа стоял SF Symbol на плашке
/// своего цвета — плашку рисовал экран, символ приходил из `badge.icon`; теперь
/// экран даёт только размер.
///
/// Ободок перекрашен под редкость ИЗ КОДА, а не из бумаг художника: тот не
/// видел `docs/achievements.md` и проставил редкости на глаз — девятнадцать
/// значков из пятидесяти восьми разошлись. Сверку держит `BadgeArtTests`.
///
/// Ассет — ВЕКТОР (`preserves-vector-representation`), хотя нарисован по
/// пиксельной сетке 128×128: пути с `shape-rendering="crispEdges"` дают
/// честные квадраты на любом размере, от 30 pt в профиле до 130 на карточке
/// «вы открыли», и одним файлом вместо трёх растров.
struct BadgeArt: View {
    /// Заработан или ещё нет. Секрета здесь нет нарочно: нераскрытый значок
    /// показывать нельзя вовсе — рисунок и есть ответ, — и вопросительный знак
    /// вместо него рисует сам экран.
    enum State { case unlocked, locked }

    let badge: Badge
    let side: CGFloat
    var state: State = .unlocked

    /// Имя ассета. Папка `Badges` в каталоге даёт пространство имён, чтобы
    /// `first_trip` не столкнулся с чужой картинкой того же имени.
    static func assetName(for id: String) -> String { "Badges/\(id)" }

    var body: some View {
        Image(Self.assetName(for: badge.id))
            .resizable()
            .scaledToFit()
            .frame(width: side, height: side)
            // Незаработанный — обесцвечен и приглушён, а не заменён серым
            // силуэтом: форму видно, и по ней значок узнаётся на полке заранее.
            // Скрытый (секретный) сюда не попадает — см. `State`.
            .saturation(state == .locked ? 0 : 1)
            .opacity(state == .locked ? 0.4 : 1)
    }
}
