import Foundation

/// Куда попадает точка, выбранная чипом («Дом», частое место, тап по карте) —
/// в «Откуда» или в «Куда».
///
/// Чистая функция, а не решение прямо в листе: тап по чипу не спрашивает,
/// какое поле сейчас в фокусе (клавиатуры может не быть открыто вовсе), а
/// решает по тому, что уже заполнено — «сначала Откуда, потом Куда».
enum ManualTripActiveField {
    case from
    case to

    /// `from` пусто → чип идёт туда. `from` заполнено, `to` пусто → идёт в
    /// `to`. Оба заполнены → чип продолжает менять `to`: это последнее поле,
    /// которое человек трогал по смыслу «сначала откуда, потом куда».
    static func resolve(from: ManualTripPoint?, to: ManualTripPoint?) -> ManualTripActiveField {
        if from == nil { return .from }
        if to == nil { return .to }
        return .to
    }
}
