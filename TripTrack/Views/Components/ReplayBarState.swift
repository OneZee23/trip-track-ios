import Foundation

/// Три состояния плашки реплея — и ЕДИНСТВЕННЫЙ источник правды о том, что
/// на ней нарисовано.
///
/// До 0.7.0 состояния не было вовсе: плашка выводила его из трёх полей движка
/// разом — `isPlaying || progress > 0 || headCoord != nil`. А `configure`
/// ставил машинку на стартовую точку ещё до нажатия «играть» (`applyFrame`
/// на нулевом кадре), то есть `headCoord` был не `nil` всегда — и «×» горел
/// на экране, где ничего не проигрывалось. Нажатие на него убирало машинку,
/// стоявшую ровно на стартовом кружке, и снаружи выглядело как мёртвая
/// кнопка. Вывод состояния из полей, которые меняет не только воспроизведение,
/// и есть поломка; чинится она не условием, а состоянием.
///
/// Переходы — чистая функция без движка и без SwiftUI, чтобы их держал тест,
/// а не открытый экран на телефоне (то же соображение, что у
/// `AutoTripPolicy` и `JourneyEditSheet.startBounds`).
enum ReplayBarState: Equatable {
    /// Зашли на экран, ничего не играли: кнопка «играть», бегунок на нуле,
    /// «×» НЕТ, машинки на карте нет и маршрут горит целиком.
    case idle
    /// Едем: иконка «пауза», бегунок движется, «×» показан.
    case playing
    /// Остановились там, где остановились: иконка «играть», бегунок на месте,
    /// «×» показан.
    case paused

    /// Что случилось. Событий ровно столько, сколько входов у плашки: две
    /// кнопки, шкала и конец дороги.
    enum Event: Equatable {
        /// Нажали кнопку «играть»/«пауза».
        case tapPlayPause
        /// Нажали «×».
        case tapStop
        /// Потянули шкалу.
        case scrub
        /// Доехали до конца — последний кадр остаётся на экране.
        case reachedEnd
    }

    /// «×» виден только там, где ему есть что убрать. В `idle` убирать нечего,
    /// поэтому его нет вовсе: кнопка, нажатие на которую ничего не меняет,
    /// хуже отсутствующей.
    var showsStop: Bool { self != .idle }

    /// Кнопка говорит, что СДЕЛАЕТ: пауза — только пока едем.
    var showsPauseIcon: Bool { self == .playing }

    /// Машинка и гашение непройденного — принадлежность начатого реплея.
    /// В `idle` карта ровно такая, какой человек её открыл.
    var showsHead: Bool { self != .idle }

    static func reduce(_ state: ReplayBarState, _ event: Event) -> ReplayBarState {
        switch event {
        case .tapPlayPause:
            return state == .playing ? .paused : .playing
        case .tapStop:
            // «×» всегда делает одно и то же и всегда что-то меняет.
            return .idle
        case .scrub:
            // Подмотка из `idle` — это уже воспроизведение, просто стоящее:
            // человек выбрал кадр и смотрит на него. Из `playing` она ничего
            // не меняет — паузу на время жеста плашка ставит сама.
            return state == .idle ? .paused : state
        case .reachedEnd:
            return state == .playing ? .paused : state
        }
    }
}
