import Foundation

/// Что экран поездки показывает в плитках энергии.
///
/// Отдельным типом, а не кортежем из шести полей: кортеж здесь уже был
/// (`tripFuelInfo` до 0.8.3) и держал ровно две плитки; с тремя, каждая из
/// которых бывает или не бывает, он превратился бы в набор опциональных
/// «volume/cost/volUnit/kWh/costLabel», где половина сочетаний не имеет смысла.
///
/// Считает состав `TripDetailView.tripEnergyInfo` из `EnergyEstimate`. Правило
/// одно и оно записано в спеке §3.4: **плитка части есть, только если у части
/// есть километры И у машины задан её расход.** «Не задано» не печатается как
/// «0 кВт·ч» — это разные ответы.
struct TripEnergyTiles {
    struct Electricity {
        let kWh: Double
    }

    struct Fuel {
        /// Литры или галлоны — уже переведённые, по приборке ЭТОЙ машины.
        let volume: Double
        /// Подпись объёма рядом с числом.
        let volUnit: String
    }

    struct Cost {
        let amount: Double
        /// «Стоимость», «Стоимость топлива» или «Стоимость электричества».
        ///
        /// Подпись говорит, У ЧЕГО эта сумма, когда цена задана только у одной
        /// половины: просто «Стоимость» рядом с деньгами за одну часть — это
        /// обещание полной суммы, которой у нас нет.
        let label: String
    }

    let electricity: Electricity?
    let fuel: Fuel?
    let cost: Cost?
    /// Символ валюты этой поездки.
    let currency: String
}
