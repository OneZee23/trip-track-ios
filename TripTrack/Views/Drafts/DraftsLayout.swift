import CoreGraphics

/// Геометрия экрана «Черновики» (спека §8).
///
/// **Формулы, не координаты** (принцип 5 спеки): верхнее считается от
/// безопасной зоны, нижнее — от верха капсулы таб-бара, диалог — от середины
/// экрана. Числа таблицы спеки это ПРОВЕРКА формул, а не их источник, и
/// сверяет их `DraftsLayoutTests` по пяти телефонам.
///
/// Тот же приём, что у `AtlasSlot` и `PlacesSlot`, и по той же причине: экран,
/// нарисованный под один телефон, разъезжается на остальных молча.
struct DraftsLayout: Equatable {
    let height: CGFloat
    let safeTop: CGFloat
    let safeBottom: CGFloat
    let width: CGFloat

    init(height: CGFloat, safeTop: CGFloat, safeBottom: CGFloat, width: CGFloat = 390) {
        self.height = height
        self.safeTop = safeTop
        self.safeBottom = safeBottom
        self.width = width
    }

    /// Верх капсулы таб-бара: он на списке стоит и не анимируется.
    ///
    /// `CustomTabBar.bottomGap` у нас 22 всегда и от индикатора «домой» не
    /// зависит (решение 0.8.1); спека считает 10 pt на телефонах без
    /// индикатора, и там наши нижние числа ровно на 12 pt ниже таблицы.
    var tabBarTop: CGFloat {
        height - CustomTabBar.bottomGap - CustomTabBar.pillHeight
    }

    /// Низ стеклянной шапки: `зона + 46`.
    var headerBottom: CGFloat { safeTop + 46 }

    /// Верх кнопки «Все мои · N»: `верх таб-бара − 64`.
    var buttonTop: CGFloat { tabBarTop - 64 }

    /// Нижний отступ содержимого: `68 + низ таб-бара + 12 + 52 + 12`.
    ///
    /// Список уходит ПОД кнопку и таб-бар, а не упирается в них: иначе
    /// последняя строка читалась бы обрезанной, а не продолжающейся.
    var listBottomInset: CGFloat { 68 + CustomTabBar.bottomGap + 12 + 52 + 12 }

    /// Верх пустого состояния — 30 % высоты экрана (доска DR-10).
    ///
    /// Долей, а не отступом от шапки: на SE и на 15 Pro Max пустая плашка
    /// обязана стоять на глаз одинаково, а расстояние от шапки на маленьком
    /// экране увело бы её к середине.
    var emptyTop: CGFloat { height * 0.30 }

    /// Ширина «Удалить» в режиме выбора — 40 % строки кнопок (спека §матрица).
    ///
    /// Точками, а не долей контейнера: две кнопки режима выбора обязаны
    /// закрывать ту же ширину, что одна кнопка обычного вида, и начинаться от
    /// того же левого поля — иначе низ экрана дёргается при входе в выбор.
    var deleteButtonWidth: CGFloat { (width - 32) * 0.4 }

    /// Верх диалога удаления: `высота / 2 − 120`.
    var dialogTop: CGFloat { height / 2 - 120 }

    /// Карта на экране поездки — 45 % высоты, как сейчас. Экран поездки эта
    /// переделка не меняет; число здесь только для сверки с таблицей спеки.
    var tripMapHeight: CGFloat { height * 0.45 }
}
