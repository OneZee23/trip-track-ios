import Foundation

/// Что рисовать, когда чужой профиль не открылся (0.6.3).
///
/// Сервер отвечает `USER_NOT_FOUND` на три разных случая сразу — аккаунта нет,
/// профиль закрыт, между вами блокировка — и делает это НАМЕРЕННО: любой другой
/// ответ превратил бы ссылку в инструмент проверки, существует ли аккаунт.
/// Клиент обязан сохранить эту неразличимость, а не «улучшить» её сообщением
/// поточнее.
///
/// Единственное исключение — когда личность уже приехала вместе с переходом
/// (`preloaded`, то есть человека только что видели в публичной ленте). Там
/// существование аккаунта и так публично, скрывать нечего, и честнее показать
/// «Закрытый профиль» с именем, чем делать вид, что его нет.
enum ProfileUnavailableState: Equatable {
    /// Личность известна из публичной ленты: имя и аватар показать можно.
    case closed(name: String, avatar: String?)
    /// Прямая ссылка. Ни имени, ни аватара, и текст не подтверждает, что
    /// аккаунт существует.
    case unavailable
    /// Всё остальное — сеть, бан, незнакомый серверный код. Это отказ загрузки,
    /// и предлагать он должен повтор, а не подписку.
    case transient

    static func from(error: APIError, preloaded: SocialAuthor?) -> ProfileUnavailableState {
        guard case .unknownServer(let code, _) = error, code == "USER_NOT_FOUND" else {
            return .transient
        }
        // Пустое имя не даёт ничего, что стоило бы показать: «Закрытый профиль»
        // под безымянным кружком читается как сломанный экран, а не как ответ.
        let name = preloaded?.displayName?.trimmingCharacters(in: .whitespaces) ?? ""
        guard !name.isEmpty else { return .unavailable }
        return .closed(name: name, avatar: preloaded?.avatarEmoji)
    }
}
