import SwiftUI

/// Значок «PRO» у имени — пилюля с пиксельным шрифтом приложения.
///
/// СЛОВОМ, а не значком, и в этом отличие от ромбика, который стоял здесь до
/// 0.8.4. Тот был выбран потому, что слово «Плюс» в тринадцати языках разной
/// длины и однажды отняло бы у имени половину строки. «PRO» не переводится ни
/// на один из них (правило версии) — длина у пилюли одна на все языки, и
/// слово читается прямо.
///
/// Шрифт — `PressStart2P`, тот же, которым набрана марка приложения на
/// постере. Он пиксельный, и это единственная роль, где он законен: своя
/// гарнитура у приложения одна (правило 0.8.1), а марка — исключение,
/// заведённое раньше.
///
/// Показывать ли значок, решает `PlusBadgeVisibility`, и решает ОДИНАКОВО в
/// четырёх местах показа: лента, комментарии, свой профиль, чужой профиль.
/// Свой значок подчиняется тумблеру приватности, чужой — нет.
struct ProBadge: View {
    /// Высота пилюли. 18 у имени в профиле (макет), меньше там, где меньше
    /// само имя: в ленте и в комментариях.
    var height: CGFloat = 18

    @EnvironmentObject private var lang: LanguageManager

    /// Кегль ФИКСИРОВАН и от высоты пилюли не зависит.
    ///
    /// Семь точек — это семь пиксельных строк глифа, ровно как нарисовано в
    /// макете (10.5 px по сетке 1.5). Вывести его из высоты значило бы на
    /// пилюле 14 получить пять с половиной точек, а пиксельный шрифт мельче
    /// шести точек превращается в кашу.
    private static let glyph: CGFloat = 7

    var body: some View {
        Text(verbatim: "PRO")
            .font(.custom("PressStart2P-Regular", fixedSize: Self.glyph))
            .foregroundStyle(.white)
            .padding(.horizontal, 6)
            .frame(height: height)
            .background(Capsule().fill(AppTheme.accent))
            // `fixedSize` по той же причине, что у пилюли «Вы» рядом: Dynamic
            // Type не имеет права сжать значок в пользу имени — сначала
            // обрезается имя.
            .fixedSize()
            .accessibilityLabel(AppStrings.plusBadgeLabel(lang.language))
    }
}

/// Показывать ли значок. Чистая функция и своя таблица в тестах: правило
/// живёт в четырёх местах показа сразу (лента, комментарии, свой профиль,
/// чужой профиль), и разъехаться им нельзя.
enum PlusBadgeVisibility {
    /// - Parameters:
    ///   - isPlus: что сказал сервер про ЭТОТ аккаунт. `nil` — старый сервер
    ///     поля не прислал, и это «не сказано», а не «нет»: значок в таком
    ///     случае не рисуется, потому что рисовать нечего, но и решения
    ///     «подписки нет» здесь не принимается.
    ///   - isOwn: своя ли это карточка.
    ///   - showsOwnBadge: `SettingsManager.showPlusBadge` — тумблер в
    ///     «Приватности». Он про СВОЙ значок и только про него: прятать чужой
    ///     значок своей настройкой приложение не имеет права.
    static func shows(isPlus: Bool?, isOwn: Bool, showsOwnBadge: Bool) -> Bool {
        guard saysPlus(isPlus) else { return false }
        return isOwn ? showsOwnBadge : true
    }

    /// «Сервер сказал, что у этого аккаунта живая подписка?»
    ///
    /// `nil` — «не сказано», и ответ на него ОДИН на всю чужую косметику:
    /// нет. Функция названа и вынесена ровно затем, чтобы фон, рамка и значок
    /// на чужом профиле спрашивали одно и то же одним способом: пока правило
    /// стояло трижды по месту, фон и рамка читали «не сказано» как «да», а
    /// значок рядом — как «нет», и спор этих двух решался в пользу худшего
    /// случая — истёкшего подписчика, у которого сервер не вычистил поле.
    static func saysPlus(_ isPlus: Bool?) -> Bool { isPlus == true }
}
