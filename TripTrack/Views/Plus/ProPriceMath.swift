import Foundation

/// Выгода годового тарифа — из цен витрины, а не из макета.
///
/// `displayPrice` у StoreKit это УЖЕ НАПЕЧАТАННАЯ строка, и своим форматтером
/// её не пересобрать: валюту, разделитель и сторону знака решает Apple, и
/// однажды мы показали бы «29.99 €» там, где витрина пишет «€29.99» (правило
/// 0.8.0). Поэтому считаем на `Decimal`, а печатаем тем же форматом, которым
/// Apple напечатала саму цену, — он приходит сюда замыканием.
///
/// Единственное место, где приложение считает деньги само. Цена ошибки —
/// отказ ревью 3.1.2 или неверно обещанная человеку выгода, поэтому тут нет ни
/// одного значения по умолчанию: нечего посчитать — подписи не будет.
enum ProPriceMath {

    /// Сколько это в месяц, если платить за год.
    ///
    /// `nil` — цены нет, формата нет или цена не положительна. Ноль и минус
    /// это не «бесплатно», а мусор на входе: делить на такое нельзя.
    static func perMonth(yearly: Decimal?, format: ((Decimal) -> String)?) -> String? {
        guard let yearly, let format, yearly > 0 else { return nil }
        return format(yearly / 12)
    }

    /// На сколько процентов год дешевле двенадцати месяцев.
    ///
    /// Округление ВНИЗ, и это не мелочь: 39.58 % нельзя объявлять сороковыми —
    /// обещание выгоды не имеет права быть больше настоящей.
    ///
    /// `nil` — посчитать не из чего, либо год не дешевле (в том числе ровно
    /// равен двенадцати месяцам). Ноль процентов на витрине читался бы как
    /// сбой показа, а не как «выгоды нет».
    static func savingPercent(yearly: Decimal?, monthly: Decimal?) -> Int? {
        guard let yearly, let monthly, yearly > 0, monthly > 0 else { return nil }
        let twelve = monthly * 12
        guard yearly < twelve else { return nil }
        let ratio = (twelve - yearly) / twelve * 100
        return Self.truncated(ratio)
    }

    /// Целая часть `Decimal` — через `NSDecimalRound`, а НЕ через
    /// `NSDecimalNumber.intValue`.
    ///
    /// `intValue` на значении с длинной мантиссой возвращает **ноль**, молча:
    /// деление `1900 / 4800 * 100` даёт 39.583333333333333333333333333333333333
    /// (38 знаков), и `intValue` на нём — 0. Поймано пробой на симуляторе, а не
    /// чтением: арифметика при этом верна, врёт только преобразование. Через
    /// `Double` тоже вышло бы 39, но тогда деньги считались бы в плавающей
    /// точке, а этого правило версии не разрешает.
    private static func truncated(_ value: Decimal) -> Int {
        var result = Decimal()
        var input = value
        NSDecimalRound(&result, &input, 0, .down)
        return NSDecimalNumber(decimal: result).intValue
    }
}
