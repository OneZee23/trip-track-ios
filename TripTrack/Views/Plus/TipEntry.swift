import Foundation

/// Видно ли вход в чаевые.
///
/// **Это ПРАВИЛО, а не вид.** До 0.8.4 здесь жила строка `ProfileSupportRow` в
/// подвале «Я»; 30 сентября 2026 владелец перенёс вход в лист настроек, в
/// карточку автора — туда, где «Написать автору» и «Телеграм-канал». Внизу
/// ленты профиля строка стояла ни с чем не рядом, а благодарность — часть
/// разговора о том, кто это сделал. Вид уехал вместе с переездом; осталось то,
/// что от него было по-настоящему нужно.
///
/// Чистой функцией, потому что ответ неочевиден: чаевые видны и ПОДПИСЧИКУ —
/// решение владельца, а не забытый гейт (спека §11: «Видны всем с витриной, и
/// с PRO, и без»). Прячет их только витрина, которая платного не продаёт: там
/// нет ни входа в чаевые, ни раздела «Подписка» (состояние 17), и платёж
/// физически не прошёл бы.
enum TipEntry {
    static func isVisible(status: ProStatus) -> Bool {
        status != .hiddenStorefront
    }
}
