import CoreGraphics

/// Explicit detents for the contextual PRO sheets, manual map and dialogs.
/// The storefront itself uses its content's natural size (0.8.8); estimating
/// its scroll range from a single fixed height clipped translated/large text.
struct ProLayout {
    let height: CGFloat
    let safeTop: CGFloat
    let safeBottom: CGFloat

    /// 25 + превью 160 + 12 + заголовок + 4 + 20 + 16 + кнопка 52 + 8 + 44 + низ.
    ///
    /// Низ здесь 34 с индикатором и **16** без него, а не 4: у листа своё поле
    /// снизу, и оно больше, чем у закреплённого подвала пейвола.
    /// Заголовок занимает две строки на длинных языках — отсюда параметр.
    func contextSheet(titleLines: Int) -> CGFloat {
        341 + (titleLines <= 1 ? 26 : 52) + sheetBottom
    }

    /// Сколько строк займёт заголовок контекстного листа.
    ///
    /// Считается по ДЛИНЕ СТРОКИ, а не по номеру момента, и это не придирка:
    /// «PRO закончился» — одна строка на любом языке, а «Уже десять поездок.
    /// Профиль можно оформить» — две, и по-немецки длиннее русского. Угадывать
    /// по моменту значит угадывать за тринадцать языков сразу.
    ///
    /// Измерять нельзя (правило «высота листа — числом»), поэтому здесь
    /// БЮДЖЕТ ЗНАКОВ на строку, и считан он для САМОГО УЗКОГО телефона в
    /// продаже: 375 pt минус поля 16 × 2 = 343 pt при кегле 20/600. На
    /// широких телефонах бюджет от этого слишком строгий — и это ровно та
    /// сторона, в которую ошибаться можно: лист на 26 pt выше нужного
    /// показывает пустое место внизу, а на 26 pt ниже — ОБРЕЗАЕТ КНОПКУ.
    ///
    /// Первая редакция считала 28 по ширине 390 pt и оставляла у самых длинных
    /// настоящих переводов запас в два знака (находка ревью). Держит это не
    /// арифметика в комментарии, а `ProLayoutTests` — он ИЗМЕРЯЕТ настоящие
    /// заголовки настоящим шрифтом и падает, если правило недооценило хоть
    /// один.
    static let titleCharactersPerLine = 26

    static func titleLines(for title: String) -> Int {
        title.count > titleCharactersPerLine ? 2 : 1
    }

    /// 25 + 48 + 172 + 29 + 58 + 12 + 29 + 72 + 12 + 12 + 52 + низ.
    var lineSheet: CGFloat { 521 + sheetBottom }

    private var sheetBottom: CGFloat { safeBottom > 0 ? 34 : 16 }

    /// Карта-герой ручной поездки — 40 % высоты экрана.
    var manualMap: CGFloat { (height * 0.4).rounded() }

    /// Верх домашнего диалога.
    ///
    /// Округляется, и это не придирка: у SE высота 667 нечётная, формула
    /// спеки даёт 213.5, а половина точки на краю карточки — мутная кромка.
    /// `tokens.json` для SE называет 214, то есть округление уже сделано там.
    var dialogTop: CGFloat { (height / 2 - 120).rounded() }
}
