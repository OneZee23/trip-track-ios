import Foundation

/// В каком состоянии витрина PRO — состояния 1, 1а, 1б, 6, 7, 9 матрицы 0.8.4.
///
/// Состояния 8 и 10 в список не входят, и почему — сказано ниже, у самих
/// случаев. Список здесь обязан совпадать с набором случаев: первая редакция
/// перечисляла «8», которого в типе нет, и противоречила себе через тридцать
/// строк (находка ревью).
///
/// Перечисление, а не набор булевых полей: состояния исключают друг друга, и
/// «идёт покупка И цены не загрузились» не существует нигде, кроме случайного
/// сочетания двух флагов. Правило проекта про взаимоисключающие состояния
/// («Swift Style»), и здесь у него есть вторая причина: половину этих
/// состояний открытым экраном не задать вовсе — `SKTestSession` не умеет ни
/// «Apple не ответила», ни «ждём одобрения владельца семейной группы».
///
/// Что где показано — свойства ЗДЕСЬ, а не `if` в `body`. Экран, который сам
/// решает, рисовать ли кнопку покупки, проверяется только глазами.
enum ProPaywallPhase: Equatable {
    /// 1а — продукты ещё едут от Apple.
    case loading
    /// 1, 4, 5 — цены есть, можно покупать.
    case priced
    /// 1б — Apple не ответила.
    case pricesFailed
    /// 6 — идёт покупка.
    case purchasing
    /// 7 — Ask To Buy: покупку одобрит владелец семейной группы.
    case pending
    /// 9 — куплено. Витрины на экране больше нет вовсе.
    ///
    /// Собирает этот экран задача 6; здесь состояние заведено с полными
    /// ответами, потому что от него зависят ВСЕ свойства ниже, и дописывать
    /// их потом означало бы править каждое.
    case bought

    // Состояния 8 («не получилось») и 10 («нечего восстанавливать») сюда НЕ
    // входят, и это чтение макета, а не пропуск: оба показывают ТОСТ поверх
    // состояния 1, а сам экран остаётся витриной с теми же тарифами и той же
    // кнопкой. Заводить им фазу значило бы завести две фазы, которые рисуются
    // одинаково, — и первый же читатель кода искал бы между ними разницу.

    /// Набор из пяти виден ВСЕГДА, пока человек ещё не купил, — в том числе
    /// когда цены не загрузились. Витрина без цен обязана остаться витриной:
    /// человек пришёл узнать, что такое PRO, и молчание в ответ хуже, чем
    /// отсутствие кнопки.
    var showsFeatureSet: Bool { self != .bought }

    /// Настоящие карточки тарифов.
    var showsPlanRow: Bool {
        switch self {
        case .priced, .purchasing:                return true
        case .loading, .pricesFailed, .pending, .bought: return false
        }
    }

    /// Скелетон на месте тарифов, пока цены едут.
    var showsTariffSkeleton: Bool { self == .loading }

    /// Карточка «Цены не загрузились · Нет связи с App Store».
    var showsPricesFailedCard: Bool { self == .pricesFailed }

    /// Карточка «Ждём подтверждения» вместо тарифов.
    var showsPendingCard: Bool { self == .pending }

    /// «Повторить» — только там, где есть что повторять.
    var showsRetry: Bool { self == .pricesFailed }

    /// Кнопка покупки. Нет её там, где покупать физически нечего (`.pricesFailed`)
    /// и где нажатие ничего не изменит (`.pending` — ждём чужого решения; там
    /// стоит «Понятно»). Нажатие, которое ничего не делает, хуже отсутствующего.
    var showsBuyButton: Bool {
        switch self {
        case .priced, .purchasing, .loading:   return true
        case .pricesFailed, .pending, .bought: return false
        }
    }

    /// Строка «Восстановить покупки · Условия · Конфиденциальность».
    ///
    /// Без цен она ОБЯЗАНА остаться: человек мог платить на другом телефоне, и
    /// именно за этим он сюда и пришёл — требование ревью Apple, а не удобство.
    /// А вот у «ждём одобрения» её нет ни в макете, ни по смыслу: покупка уже
    /// сделана, восстанавливать нечего, и предлагать это человеку, который
    /// ждёт чужого решения, значит подсказывать ему, что что-то сломалось.
    ///
    /// Одно свойство, а не два («ссылки» и «восстановление»): кнопка
    /// восстановления живёт ВНУТРИ этой строки, и вопрос у них один.
    /// Прежнее `showsRestore` было мертво по построению — единственная фаза,
    /// где оно отвечало `false`, до подвала не доходила вовсе (находка ревью).
    var showsLinks: Bool {
        switch self {
        case .priced, .purchasing, .loading, .pricesFailed: return true
        case .pending, .bought:                             return false
        }
    }

    /// Пока идёт покупка, тариф не переключить: системный лист Apple уже
    /// открыт на ТОМ продукте, и смена выбора под ним рассинхронизировала бы
    /// экран с покупкой.
    var allowsTariffChange: Bool {
        switch self {
        case .priced: return true
        default:      return false
        }
    }

    /// Крестик гаснет только на время покупки — иначе человек закроет лист в
    /// середине системного диалога Apple и не узнает, чем всё кончилось.
    var allowsClose: Bool { self != .purchasing }

    var showsSpinnerInButton: Bool { self == .purchasing }

    /// Что стоит на месте главной кнопки.
    ///
    /// ЗНАЧЕНИЕМ, а не цепочкой `if/else if` в теле вида, и это не стиль:
    /// ревью показало, что удаление ветки «Понятно» из `actionArea` не ловит
    /// ни один тест — свойства фазы остаются верными, а кнопка с экрана
    /// исчезает, и состояние 7 остаётся карточкой без выхода. Исчерпывающий
    /// `switch` по этому типу превращает такую потерю в ошибку КОМПИЛЯЦИИ,
    /// а сам выбор — в то, что проверяется таблицей.
    enum FooterAction: Equatable {
        /// Кнопка покупки (в `.loading` — пустая и приглушённая).
        case buy
        /// «Повторить» — цены не загрузились.
        case retry
        /// «Понятно» — ждём чужого одобрения, нажатие закрывает лист.
        case acknowledge
        /// Кнопки нет вовсе.
        case none
    }

    var footerAction: FooterAction {
        switch self {
        case .priced, .purchasing, .loading: return .buy
        case .pricesFailed:                  return .retry
        case .pending:                       return .acknowledge
        case .bought:                        return .none
        }
    }

    /// Тарифы и крестик на 40 % (состояние 6).
    var dimsChrome: Bool { self == .purchasing }
}
