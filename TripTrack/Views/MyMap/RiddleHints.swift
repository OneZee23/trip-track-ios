import Foundation

/// Флаг видимости подсказок нерешённых загадок на «Атласе».
///
/// Владелец 17 сентября 2026: убрать загадки из видимости, включить в одной
/// из следующих версий. Секреты уже засчитываются на финише, а историй для
/// карточки загадки пока нет — показывать круг «где-то здесь» раньше
/// рассказа не о чем.
///
/// `RiddleHint.plan` — ЕДИНСТВЕННЫЙ источник подсказок: аннотации на карте,
/// гравировка в тумане (и растр, и плиточный откат), журнал «Загадки рядом»
/// и счётчик в его заголовке — все читают то, что вернул `plan`. Гейт стоит
/// РОВНО там: выключенная видимость значит пустой список из `plan`, и вся
/// остальная цепочка молчит сама, без отдельных проверок флага по пути.
///
/// Зачёт загадки на финише (`DiscoveryProcessor`/`RiddleMatcher`) флаг не
/// трогает — «скрыты из видимости», а не выключены: решённая загадка
/// становится печатью независимо от того, стоял ли её круг на карте.
enum RiddleHints {
    static let isEnabled = false

    /// Тестовый шов. Юнит-тесты самой математики круга (`RiddleHintTests` и
    /// другие, зовущие `RiddleHint.plan` напрямую) обязаны видеть подсказки
    /// независимо от прод-константы выше — `nil` значит «как в проде».
    /// Тест, выставивший `true`, обязан вернуть `nil` в `tearDown`: иначе он
    /// «роняет чужой класс» (см. CLAUDE.md «Ловушки, на которые уходит по
    /// часу» — хвост, не обнулённый между тестами).
    static var isEnabledOverride: Bool?

    static var isActive: Bool { isEnabledOverride ?? isEnabled }
}
