import CoreGraphics

/// Видна ли подпись региона на этом масштабе.
///
/// Единственный вопрос — bbox края на экране (в точках): читается ли имя
/// вообще. Порог — 140 pt, заголовок вроде «КРАСНОДАРСКИЙ КРАЙ» без обрезки.
///
/// Подпись НЕ гаснет на дальнем уровне, хотя изначально гасла. Она
/// существует только у ПОСЕЩЁННОГО региона (`regionLabels(visitedRegionIds:)`),
/// и порога в 140 pt хватает, чтобы край, сжавшийся до пикселя, всё равно
/// молчал: его отсекает bbox, а не ярус слоя открытого.
///
/// Страны (свой, более низкий порог и «только на дальнем уровне») были здесь
/// до 17 сентября — их подписи и контуры на «Атласе» убраны вместе:
/// геополитика на карте нам не нужна, а контур у Японии и Филиппин к тому же
/// был заметно смещён на мировом зуме.
enum RegionLabelLOD {
    static let regionMinSidePt: CGFloat = 140

    static func level(bboxMinSidePt: CGFloat) -> Bool {
        bboxMinSidePt >= regionMinSidePt
    }
}
