import Foundation

/// Спайк «метал-туман»: выкидной, ради одного взгляда на устройстве.
///
/// Владелец отверг нынешнюю мглу «Атласа» — один растр CoreGraphics, который
/// перерисовывается только когда камера встала, а на жесте растягивается: мыло
/// под пальцем, видимая «перезагрузка» после и кольца вокруг коридоров. Fog of
/// World рисует то же самое вектором на GPU каждый кадр и ничего из этого не
/// показывает. Флаг включает второй туман — метал-вуаль — и глушит растровый,
/// оставляя вуали её векторные слои (жилка сети и выбранный маршрут).
///
/// Только в Debug и только на «Атласе». Ни экран поездки, ни экран записи,
/// ни постер этим флагом не затронуты.
enum FogMetalSpike {
    static var isEnabled: Bool {
        #if DEBUG
        return true
        #else
        return false
        #endif
    }
}
