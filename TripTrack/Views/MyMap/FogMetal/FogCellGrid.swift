import MapKit

/// Сетка «Клеток» — третьего стиля карты «Атласа» (макет A7 «Вид карты»).
///
/// Туман в нём открывается не мягким коридором, а КВАДРАТАМИ: клетка либо
/// открыта целиком, либо закрыта целиком.
///
/// **Сторона — постоянное число ТОЧЕК КАРТЫ, а не метров, и это решение.**
/// Метрическая сторона считалась бы от широты центра кадра, а её крошечное
/// изменение при панораме перефазирует всю мировую сетку: индекс клетки это
/// `minY / side`, у Краснодара он около ста сорока тысяч, и сдвиг стороны на
/// сотую долю точки уводит индекс на полторы клетки. На экране это выглядит
/// как сетка, скачущая под пальцем. Поймано пиксельным тестом
/// (`testCellsAreAnchoredToTheWorldNotTheViewport`), а не глазами.
///
/// Точки карты — меркаторская единица, и проекция конформна: клетка в них
/// квадратна на любой широте, просто её земной размер меняется — ≈76 м у
/// экватора, ≈54 м на широте Краснодара, ≈38 м на шестидесятой. Порядок тот
/// же, что у `RevealGrid` (75 м), и это не совпадение: клетки показывают ту
/// же ячейку, которой слой открытого и хранится. Совпасть ТОЧНО они не могут
/// — у той сетка градусная и потайловая, и она сама говорит, что ячейки из
/// разных тайлов несравнимы.
///
/// Эталонный «Туман» этот стиль НЕ трогает: квантование живёт в КОМПОЗИТНОМ
/// проходе, а проход покрытия остаётся байт в байт прежним (решение владельца
/// 26 сентября: «сделать, эталон не трогая»).
struct FogCellGrid: Equatable {
    /// Сторона клетки в точках карты.
    let sideMapPoints: Double
    /// Смещение ближайшей границы сетки ПЕРЕД углом кадра — от этого угла, в
    /// точках карты. Считается в `Double` на CPU и приезжает в шейдер уже
    /// маленьким числом: абсолютная координата в Float32 не помещается (та же
    /// причина, по которой у меша куски со своими началами).
    let originOffset: CGPoint
    /// Сторона в точках ЭКРАНА — нужна только тому, кто решает, рисовать ли
    /// сетку вообще.
    let sideScreenPoints: Double

    /// Базовая сторона — степень двойки: `floor(координата / side)` на ней
    /// точен в `Double` при любой координате мира, и границы ложатся на
    /// границы кусков меша (те по `32768`). ≈76 м у экватора, ≈54 м на широте
    /// Краснодара — порядок `RevealGrid`.
    static let baseMapPoints: Double = 512

    /// **Сторона РАСТЁТ с отдалением, удваиваясь.** Клетка в 54 м на экране
    /// города это две точки — не клетка, а шум; стиль, который виден только
    /// на дворе, не стиль. Поэтому берётся наименьшая `base × 2^k`, дающая
    /// читаемый квадрат.
    ///
    /// Удвоение, а не «подогнать под 14 точек»: клетки соседних масштабов
    /// тогда ВЛОЖЕНЫ — при отдалении четыре сливаются в одну, а не
    /// перекладываются заново. Границы при этом остаются границами и базовой
    /// сетки, то есть мировая привязка не теряется ни на одном шаге.
    static let minScreenPoints: Double = 14

    /// Дальше клетка перестаёт что-либо значить: на мировом масштабе она
    /// накрывала бы страну. Выше потолка стиль молча падает на обычный туман.
    static let maxDoublings = 12

    /// Сетка для видимого прямоугольника кадра, или `nil` — если даже
    /// предельное удвоение не даёт читаемой клетки.
    static func make(visible: MKMapRect, viewportPoints: CGSize) -> FogCellGrid? {
        guard viewportPoints.width > 0, visible.width > 0, visible.width.isFinite else { return nil }
        let pointsPerMapPoint = Double(viewportPoints.width) / visible.width
        guard pointsPerMapPoint.isFinite, pointsPerMapPoint > 0 else { return nil }

        var side = baseMapPoints
        var screen = side * pointsPerMapPoint
        var doublings = 0
        while screen < minScreenPoints, doublings < maxDoublings {
            side *= 2
            screen *= 2
            doublings += 1
        }
        guard screen >= minScreenPoints, screen.isFinite else { return nil }

        // Граница сетки перед углом кадра. Отрицательное смещение — угол
        // стоит ВНУТРИ клетки, и её начало осталось позади.
        let originX = (visible.minX / side).rounded(.down) * side - visible.minX
        let originY = (visible.minY / side).rounded(.down) * side - visible.minY
        return FogCellGrid(sideMapPoints: side,
                           originOffset: CGPoint(x: originX, y: originY),
                           sideScreenPoints: screen)
    }
}
