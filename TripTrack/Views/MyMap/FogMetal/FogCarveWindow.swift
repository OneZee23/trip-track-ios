import CoreGraphics

/// Окно под подписью Apple Maps — то же самое, что у растровой вуали, только
/// четырьмя числами для шейдера.
///
/// Правило 0.7.0 здесь не меняется ни в чём: мглу под «Maps / Legal»
/// ПРИГЛУШАЮТ, а не снимают. Полное снятие открывало под подписью дневную
/// карту «Атласа», и владелец второй раз увидел там «яркую голубую плашку»
/// (задача A2, 21 сентября). Поэтому у окна есть ПОЛ (`floor`): в середине
/// альфа мглы умножается на него, за пером остаётся нетронутой.
///
/// Тип отдельный от `AttributionCarve` нарочно. Тот знает про дерево вью,
/// ищет подпись по именам классов и живёт на главном актёре; этому хватает
/// коробки и трёх чисел — их уносит в буфер кадра `FogFrameEncoder`, и
/// офскрин постера собирает ровно такое же окно, ничего не зная про UIKit.
struct FogCarveWindow: Equatable {
    /// Коробка окна в ТОЧКАХ вида — уже с полем (`AttributionCarve.padding`),
    /// ровно как её отдаёт `AttributionCarve.carveRect(in:space:)`.
    let rect: CGRect
    /// Радиус скругления коробки.
    let corner: CGFloat
    /// Ширина непрерывного спада наружу от коробки.
    let feather: CGFloat
    /// Во сколько раз мгла слабее в середине окна. НЕ ноль — см. докстринг.
    let floor: CGFloat

    /// Окно под атрибуцией. Числа берутся из `AttributionCarve` и только
    /// оттуда: у растровой маски (`VeilCarveMask`) они те же самые, и два
    /// набора одних и тех же чисел однажды разъехались бы молча — как
    /// разъезжались когда-то два счёта открытых километров.
    @MainActor
    static func attribution(rect: CGRect) -> FogCarveWindow {
        FogCarveWindow(rect: rect,
                       corner: AttributionCarve.corner,
                       feather: AttributionCarve.feather,
                       floor: AttributionCarve.windowFloor)
    }
}
