import CoreGraphics

/// Прорезь у машины на живой записи — то же самое, что маска
/// `VeilRevealMask` у растровой вуали, только тремя числами для шейдера.
///
/// Почему у метала это НЕ маска. У растра «перерисовать туман» значит собрать
/// восьмимегабайтную картинку: сорок миллисекунд за кадр при шестидесяти
/// кадрах в секунду, — поэтому дыра там живёт слоем-маской поверх готового
/// растра. Метал рисует мглу заново КАЖДЫЙ кадр, и дыра в нём — это два
/// умножения во фрагменте: `setLiveReveal` стоит ровно двух чисел в буфере.
///
/// Перья те же, что у кисти (`FogVeilPainter.punchReveal`) и у маски: до
/// `solid` радиуса открыто полностью, дальше ЛИНЕЙНЫЙ спад до края. Разойтись
/// этим трём нельзя — человек видит их в одну и ту же секунду, когда карта
/// откатывается на растр или на плиточный рендерер.
struct FogRevealCircle: Equatable {
    /// Середина прорези в ТОЧКАХ вида. Считает её зовущий по карте: прорезь
    /// привязана к ЗЕМЛЕ, а не к экрану, и на едущей карте её место меняется
    /// каждым кадром.
    let centre: CGPoint
    /// Радиус в точках. Ноль — прорези нет вовсе, и шейдер не трогает альфу.
    let radius: CGFloat
    /// Доля радиуса, открытая ПОЛНОСТЬЮ.
    let solid: CGFloat

    init(centre: CGPoint, radius: CGFloat, solid: CGFloat = VeilRevealMask.solidFraction) {
        self.centre = centre
        self.radius = radius
        self.solid = solid
    }
}
