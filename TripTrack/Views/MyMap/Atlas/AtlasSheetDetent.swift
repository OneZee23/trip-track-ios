import Foundation

/// Положение шторки «Атласа» (спека §4, доска S1).
///
/// Их три, и они не равноправны: `peek` руками не достаётся вовсе — в него
/// шторку уводит выбор места, и ровно тогда слот занимает карточка места.
/// «Один слот у нижнего края» (принцип 1) значит, что сводка и карточка
/// места не показываются одновременно НИКОГДА.
enum AtlasSheetDetent: Equatable, CaseIterable {
    /// Одна строка подсказки под карточкой места. Только программно.
    case peek
    /// Состояние по умолчанию: ручка, «Исследовано» и тройка чисел.
    case collapsed
    /// Весь список со скроллом внутри.
    case expanded
}

/// Из чего сложена свёрнутая шторка — и, значит, какой она высоты.
///
/// Высота задаётся ЧИСЛОМ, а не измерением содержимого, и это правило из
/// CLAUDE.md, купленное дважды сломанным экраном: у листов «Атласа» внутри
/// `ScrollView`, измерение уходит вниз и не возвращается. Числа взяты из
/// `tokens.json → layout.sheet.collapsed_by_content` и воспроизводят таблицу
/// спеки один в один.
enum AtlasSummaryVariant: Equatable {
    /// Обычная сводка (состояния 1, 7, 11).
    case summary
    /// «В эти дни поездок не было» (8) и «Не удалось обновить» (23): карточка
    /// в одну строку, шторка ниже.
    case shortCard
    /// Пустой атлас (10): карточка и одна фраза под ней.
    case emptyAtlas
    /// Строка записи или строка офлайна над сводкой (12, 24).
    case withNoticeRow

    /// Высота содержимого свёрнутой шторки в точках.
    var contentHeight: CGFloat {
        switch self {
        case .summary: return 166
        case .shortCard: return 158
        case .emptyAtlas: return 176
        case .withNoticeRow: return 222
        }
    }
}
