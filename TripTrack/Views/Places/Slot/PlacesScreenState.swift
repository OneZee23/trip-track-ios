import Foundation

/// Чем вкладка «Места» пуста — и на какой высоте она при этом стоит
/// (состояния 13, 14 и 15 спеки «Места v2»).
///
/// Три ответа, а не два. До 0.8.2 условие было одно на всех — «ни мест, ни
/// подсказок», — и вкладка БЕЗ мест, но С подсказками уходила в половину
/// (380) вместо пустой (280): подсказка отменяла пустоту, хотя мест от неё
/// не появлялось. По матрице состояние 14 стоит там же, где 13, — подсказки
/// в нём идут первой секцией, а не меняют форму экрана.
///
/// Чистым типом, потому что вопрос решается тремя числами и проверяется
/// таблицей, а не открытым экраном.
enum PlacesEmptyState: Equatable {
    /// Места есть: обычная вкладка, панель тянется.
    case notEmpty
    /// Мест нет, но поездки есть (13 и 14): образец, «Мест пока нет»,
    /// «Отметить в поездке» и подсказки, если они посчитались.
    case noPlaces
    /// Ни одной поездки (15): одна фраза, нажатий нет. Панель стоит на
    /// ПОЛОВИНЕ, а не на пустой: показывать там нечего, и лишние двести
    /// точек панели были бы пустотой ради пустоты.
    case noTrips

    /// `places` — сколько мест в библиотеке, `trips` — сколько поездок видно
    /// вкладке. Подсказки в этот вопрос НЕ входят: они меняют содержимое
    /// панели, а не её высоту.
    static func resolve(places: Int, trips: Int) -> PlacesEmptyState {
        guard places == 0 else { return .notEmpty }
        return trips == 0 ? .noTrips : .noPlaces
    }

    /// Пустые состояния держат одно положение и не тянутся (спека §4).
    var isPinned: Bool { self != .notEmpty }

    /// Куда встаёт панель. `.empty` сюда попадает ТОЛЬКО отсюда — пальцем в
    /// него не уйти (`PlacesPanelStop.draggable` его не знает), и это условие
    /// спеки, а не совпадение.
    func stop(in slot: PlacesSlot) -> PlacesPanelStop {
        switch self {
        case .notEmpty: return slot.defaultStop
        case .noPlaces: return .empty
        // На SE половины нет вовсе, и `defaultStop` там список: пустая
        // вкладка без поездок так же честна списком, как половиной.
        case .noTrips: return slot.defaultStop
        }
    }
}

/// Что показывает панель, пока человек ищет (состояния 10 и 11).
///
/// Поиск на этой вкладке — МОДАЛЬНОЕ состояние, а не поле внутри списка:
/// фокус поднимает панель в полный список, гасит заголовок вкладки и кладёт
/// на карту скрим. Поэтому и ответ у него свой, не «пустая выдача списка».
enum PlacesSearchOutcome: Equatable {
    /// Запрос пуст: поле открыто, но ищем мы пока ничего — список как был.
    case idle
    /// Совпадения. Строками сразу под полем, БЕЗ заголовка секции: заголовок
    /// «Мои места» над выдачей поиска отвечал бы на вопрос, которого никто не
    /// задавал.
    case matches
    /// Ничего не нашли (11): лупа, две строки, ни одной кнопки. Кнопке тут
    /// некуда вести — «Отмена» уже стоит у поля.
    case nothingFound

    /// `matches` — сколько строк осталось после фильтра.
    ///
    /// Пробелы не считаются запросом: поле с одним пробелом это ещё не
    /// поиск, и показывать над полным списком «Ничего не нашли» нельзя.
    static func resolve(query: String, matches: Int) -> PlacesSearchOutcome {
        let term = query.trimmingCharacters(in: .whitespacesAndNewlines)
        if term.isEmpty { return .idle }
        return matches == 0 ? .nothingFound : .matches
    }
}
