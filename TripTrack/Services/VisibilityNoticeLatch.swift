import Foundation

/// Показывали ли уже разовую карточку «профиль теперь показывает больше» (0.6.3).
///
/// 0.6.3 включил пер-блочную видимость публичного профиля с дефолтом «всё
/// открыто». Дефолт выбран сознательно — иначе фича родилась бы мёртвой, все
/// профили были бы пустыми, — но у существующих аккаунтов наружу поехало то, на
/// что они не подписывались. Единственное, что делает такой дефолт честным, это
/// сказать о нём вслух ровно один раз и рядом положить настройку.
///
/// Правило то же, что у `ProfileSyncLatch`: **отсутствующая запись означает «не
/// показывали»**. Аккаунты, обновившиеся до появления этой защёлки, записи не
/// имеют — и это ровно те, кому карточку и надо показать. Ошибиться можно
/// только в одну сторону: лишний показ раздражает, пропущенный оставляет
/// человека в неведении о том, что о нём стало видно другим.
enum VisibilityNoticeLatch {
    private static let shownKey = "com.triptrack.visibility.noticeShown"

    /// Карточку показали и человек её закрыл (или ушёл в настройки).
    static func markShown(_ defaults: UserDefaults = .standard) {
        defaults.set(true, forKey: shownKey)
    }

    /// Выход из аккаунта. Следующий Apple ID на этом телефоне — другой человек
    /// с другим публичным профилем, и он тоже имеет право узнать.
    static func reset(_ defaults: UserDefaults = .standard) {
        defaults.removeObject(forKey: shownKey)
    }

    /// Пора ли показать карточку.
    ///
    /// Гостю — никогда: у него нет публичного профиля, и «о вас стало видно
    /// больше» было бы просто неправдой.
    ///
    /// И только там, где её текст — правда. У аккаунта с ВЫКЛЮЧЕННЫМ публичным
    /// профилем ничего наружу не поехало: «о вас стало видно больше» было бы
    /// прямой неправдой, а заодно первым, что человек прочитает про приватность.
    /// `nil` (сервер ещё не ответил) — тоже не время: покажем на следующем
    /// заходе, когда будет что утверждать.
    static func needsShow(
        isSignedIn: Bool,
        isPublicProfile: Bool? = nil,
        defaults: UserDefaults = .standard
    ) -> Bool {
        guard isSignedIn, isPublicProfile == true else { return false }
        return !defaults.bool(forKey: shownKey)
    }
}
