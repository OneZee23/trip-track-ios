import Foundation

/// Когда уместно тихо предложить сказать спасибо — ЧИСТОЙ функцией.
///
/// **Почему это НЕ четвёртый момент `ProContextOffer`.** Тот отвечает на
/// «когда предложить купить», и три его главных правила здесь противоположны:
/// он молчит у подписчика (а чаевые видны и подписчику — решение владельца,
/// спека §11), он запрещает себе появляться сразу после записанной поездки
/// («человек смотрит на свой итог, а не на витрину») — а у чаевых это ровно
/// тот единственный момент, ради которого всё и делается, — и он считает
/// отказы по своей шкале. Добавить сюда четвёртый момент значило бы обвесить
/// исключением каждый его гейт и сломать работающую политику ради чужого
/// вопроса. Форма правил общая нарочно, ответ — свой.
///
/// **Правило, из которого всё выведено: сначала дать, потом тихо спросить.**
/// Поэтому спрашиваем не в настройках и не по расписанию, а на карточке итогов
/// — в ту секунду, когда приложение только что показало человеку его дорогу.
/// И спрашиваем редко: подарок просят не чаще, чем раз в полгода, и только у
/// того, кто прожил с приложением месяц и два десятка поездок.
///
/// Проверить это открытым экраном нельзя — на «раз в 180 дней» ушло бы
/// полгода, — а ошибка в любом из правил выглядит как приложение, которое
/// клянчит. Отсюда чистая функция и таблица тестов.
enum TipMoment {

    /// Раньше двадцати поездок не спрашиваем. Это ВЫШЕ порога предложения PRO
    /// (там пять): продать — обмен, а подарок просят только у того, кому
    /// приложение уже успело пригодиться.
    static let minTrips = 20
    /// И раньше месяца с приложением — тоже нет.
    static let minDays = 30
    /// «Заметная дорога» — сто километров. В МЕТРАХ и человеку не
    /// показывается: это порог логики, как у `TripDistanceGate`, а не число на
    /// экране (правило единиц 0.6.7).
    ///
    /// Сто, а не тридцать: у поездки на сотню километров есть что вспомнить, и
    /// именно на ней приложение отработало заметно. Городской человек в этот
    /// момент не попадёт вовсе — и это правильный ответ, а не пробел: просить
    /// подарок за дорогу до магазина не за что.
    static let notableMetres: Double = 100_000
    /// Не чаще раза в полгода.
    static let cooldownDays = 180
    /// А после «не сейчас» — раз в год.
    static let cooldownAfterDeclineDays = 365
    /// Два отказа — больше не спрашиваем НИКОГДА. Строка в подвале «Я»
    /// остаётся: человек, передумавший через год, найдёт её сам.
    static let maxDeclines = 2
    /// Уже поблагодарил — год тишины. Не «никогда»: тот, кто дал раз, чаще
    /// всего и есть тот, кто захочет ещё. Но спросить его снова через месяц
    /// было бы худшим, что можно сделать с этим человеком.
    static let quietAfterTipDays = 365

    /// Всё, от чего зависит ответ. Структурой, а не десятью параметрами — тот
    /// же довод, что у `ProContextOffer.Input`: половина из них одного типа, и
    /// однажды они приехали бы в другом порядке.
    struct Input {
        var now: Date
        /// Витрина платного не продаёт (РФ) или платное выключено флагом —
        /// чаевых на экране не бывает вовсе, как и всего остального
        /// (правило `PlusGate`).
        var storefrontHidesPlus: Bool
        /// Длина ТОЛЬКО ЧТО завершённой поездки, метры.
        var tripDistanceMetres: Double
        /// Черновик ещё не вошёл в мир и не подтверждён как своя поездка
        /// (правило 0.8.1). Спрашивать за чужую дорогу нельзя.
        var isDraft: Bool
        /// Сколько поездок всего.
        var tripCount: Int
        /// Когда человек впервые запустил приложение. `nil` — не знаем, и
        /// «месяц» считать не от чего: молчим.
        var firstLaunchAt: Date?
        var lastAskedAt: Date?
        var declines: Int
        var tippedAt: Date?
        /// Только что была ошибка — сеть, синк, покупка. То же правило, что у
        /// предложения PRO: человек и так расстроен.
        var afterFailure: Bool
    }

    /// Спросить ли сейчас.
    ///
    /// Порядок проверок — от «не обсуждается» к порогам, и переставлять его не
    /// надо: он и есть правило. Первыми стоят те, при которых чаевых не
    /// существует в принципе.
    static func shouldAsk(_ input: Input) -> Bool {
        // Платного нет на экране вовсе.
        if input.storefrontHidesPlus { return false }
        // Черновик — не его дорога, пока он не сказал «Моя».
        if input.isDraft { return false }
        // После ошибки не просят.
        if input.afterFailure { return false }
        // Сказал «нет» дважды — вопрос закрыт навсегда.
        if input.declines >= maxDeclines { return false }

        // Уже благодарил — год тишины.
        if let tippedAt = input.tippedAt,
           days(from: tippedAt, to: input.now) < quietAfterTipDays { return false }

        // Пороги «пожил с приложением».
        if input.tripCount < minTrips { return false }
        guard let firstLaunchAt = input.firstLaunchAt,
              days(from: firstLaunchAt, to: input.now) >= minDays else { return false }

        // Дорога должна быть заметной.
        if input.tripDistanceMetres < notableMetres { return false }

        // И не чаще, чем раз в положенный срок.
        if let lastAskedAt = input.lastAskedAt {
            let cooldown = input.declines > 0 ? cooldownAfterDeclineDays : cooldownDays
            if days(from: lastAskedAt, to: input.now) < cooldown { return false }
        }

        return true
    }

    /// Целых суток между двумя датами. Отрицательная разница (часы телефона
    /// уехали назад) читается как ноль: это «только что», а не «давно».
    private static func days(from: Date, to: Date) -> Int {
        max(0, Int(to.timeIntervalSince(from) / 86_400))
    }
}
