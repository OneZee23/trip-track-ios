import Foundation

/// Ровно пять мест, где «Плюс» открывает что-то, и ни одного больше —
/// спека §2. Четыре косметики и одна функция; список закрыт нарочно, чтобы
/// новая платная вещь была решением в диффе (новый case), а не тихой строкой
/// внутри чужого экрана.
enum PlusFeature: CaseIterable {
    /// Восемь премиум-фонов профиля.
    case profileBackgrounds
    /// Рамка аватара — шесть вариантов.
    case avatarFrame
    /// Фон карточки машины в гараже — восемь вариантов.
    case vehicleCardStyle
    /// Цвет линии маршрута на своих картах.
    case routeLineStyle
    /// Ручная поездка — маршрут по дорогам между точками, без GPS.
    case manualTrip
}

/// Что видит экран у конкретной фичи ПРЯМО СЕЙЧАС.
enum PlusAccessLevel {
    /// Витрина не продаёт платное (РФ) — фичи, пункта, замка нет вовсе, а не
    /// «есть, но недоступно»: спека §1 требует, чтобы платного не было
    /// видно на экране, не только чтобы оно не покупалось.
    case hidden
    /// Плюса нет, витрина продаёт — замок, тап уводит в `PlusPaywallSheet`.
    case locked
    /// Плюс активен — фича работает.
    case open
}

/// Единственная дверь, через которую фича спрашивает «мне можно?».
///
/// Одна чистая функция и тест-таблица 3×5 — так решение «что показывать»
/// проверяется без пяти экранов и без StoreKit. Все пять точек входа обязаны
/// звать её, а не читать `PlusAccess.shared.isPlus` напрямую: до этой функции
/// решение «РФ не видит платное» жило бы в каждом экране отдельно и однажды
/// разошлось бы на одном из них — ровно как штрафовало единицы измерения до
/// `Measure`.
enum PlusGate {
    /// - Parameters:
    ///   - feature: какая из пяти вещей спрашивает. Сегодня все пять отвечают
    ///     одинаково; параметр существует, чтобы будущая фича с другим
    ///     правилом не переписывала сигнатуру у всех пяти вызывающих.
    ///   - isPlus: `PlusAccess.shared.isPlus` — подписка активна сейчас
    ///     (триал, оплата, грейс).
    ///   - storefrontHidesPlus: `PlusAccess.shared.storefrontHidesPlus` —
    ///     витрина устройства (`Storefront.current.countryCode == "RUS"`)
    ///     не продаёт платное. Решение владельца 19 сентября.
    ///
    /// Порядок проверок не переставить: уже купленный «Плюс» обязан честно
    /// работать даже на витрине, которая платное больше не продаёт (человек
    /// мог купить на другой витрине или до смены региона) — поэтому `isPlus`
    /// проверяется ПЕРВЫМ, и только когда его нет, решает витрина.
    static func allows(
        _ feature: PlusFeature,
        isPlus: Bool,
        storefrontHidesPlus: Bool
    ) -> PlusAccessLevel {
        if isPlus { return .open }
        if storefrontHidesPlus { return .hidden }
        return .locked
    }
}
