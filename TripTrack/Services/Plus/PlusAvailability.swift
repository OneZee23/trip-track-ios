import Foundation

/// Глобальный выключатель платного.
///
/// 0.8.0 уезжает в стор с ВЫКЛЮЧЕННЫМ «Плюсом» (решение владельца 21 сен
/// 2026: товары в App Store Connect ещё не заведены, ручную поездку он хочет
/// доделать отдельно). Выключенный «Плюс» — это ровно витрина без платного,
/// та же, что у РФ: ни пейвола, ни замков, ни доната, ни косметики, ни входа в
/// ручную поездку. Код и бэкенд остаются на месте, включение — одна константа
/// в 0.8.1 ПОСЛЕ того, как пять товаров в ASC получат «Ready to Submit».
///
/// Единственный потребитель — `PlusStore.hidesPlus(countryCode:available:)`,
/// через него проходят и посев `PlusAccess.storefrontHidesPlus`, и ответ
/// StoreKit о витрине; второй проверки этого флага в коде быть не должно.
enum PlusAvailability {
    static let isEnabled = false
}
