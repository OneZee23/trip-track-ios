import Foundation

/// Кто из двух загрузок тумана имеет право лечь на карту — последняя ЗАПУЩЕННАЯ,
/// а не последняя ответившая.
///
/// На карточке итогов оба пути живут одновременно, и это не редкий случай, а
/// норма: карта просит слой при установке (`loadFog(before: nil)`), а секундой
/// позже финиш постит `.revealedLayerChanged`, и наблюдатель просит его заново,
/// уже свежим. Первая задача при этом досчитывается: `TemporalFogCache
/// .invalidate()` её отменяет, но `RevealedLayerStore.layer(before:)` отмену не
/// проверяет нигде — то есть возвращается ДОТУРИСТИЧЕСКИЙ слой. Кто из двух
/// возобновится последним, не определено, и если это будет первая, она снимет
/// свежую вуаль и поставит вчерашнюю — на том самом экране, ради которого весь
/// временной туман и заводили («карточка итогов — это момент раскрытия»).
///
/// Тот же приём, что `loadGeneration` в `MyMapViewModel.reload`. Отдельным
/// типом — потому что правило проверяется тестом, а не финишем поездки.
struct FogLoadSequencer {
    private var issued = 0

    /// Запустили загрузку — вот её номер.
    mutating func begin() -> Int {
        issued += 1
        return issued
    }

    /// Всё ещё последняя? `false` — молча выйти, её ответ уже никому не нужен.
    func isCurrent(_ token: Int) -> Bool { token == issued }
}
