import Foundation

/// Глобальный выключатель находок — секретов, загадок и вех.
///
/// Владелец 22 сентября 2026: находки откладываются до после 1.0.0. ЕДИНСТВЕННЫЙ
/// флаг, той же формы, что `PlusAvailability` у платного и `RiddleHints` у
/// подсказок загадок на «Атласе» — гейт стоит РОВНО в пяти местах, второй
/// проверки этого флага в коде быть не должно:
///
/// 1. `MapViewModel` — после `RevealedLayerStore.ingest` на финише: выключено
///    значит `DiscoveryProcessor.shared.process` не зовётся, а собирается
///    `TripDiscoveries` только с километрами и регионами из дельты тумана
///    (секреты/загадки/вехи пустые) — строка «открыто N км» и выгорание героя
///    экрана итогов остаются живыми, они про туман, не про находки.
/// 2. `MyMapViewModel.reloadDiscoveries` — печати и подсказки загадок пустые,
///    журнал собирается без них, отложенный `focusDiscovery` сбрасывается.
/// 3. `TripTrackApp` — `CachedSecretCatalog.shared.refreshIfNeeded()` не
///    зовётся: сети скрытой фиче не положено.
/// 4. `MyMapSheet` — группа «Находки» в журнале (шапка, пустая строка, сетка
///    печатей) не рисуется вовсе.
/// 5. `socialFindsAreVisible` — секция находок на чужом профиле тоже гаснет.
///
/// Половина «Атласа» про открытый мир (туман, километры, регионы, журнал
/// «Открыто») флаг НЕ трогает — она осталась полностью живой.
///
/// Что флаг СОЗНАТЕЛЬНО не выключает: пул продолжает класть строки находок в
/// `DiscoveryStore` (`PullApplier`), `LocalDataWipe` стирает их при удалении
/// аккаунта как и раньше, `POST /secrets/forget-all` уходит вместе с прочим
/// стиранием, а уже поставленные в очередь `.discovery`-раскрытия
/// (`APISyncTransport`/`DiscoveryReveal.retry`) продолжают повторяться. Данные
/// обязаны остаться согласованными на тот день, когда флаг вернут обратно —
/// разбирать рассинхрон между «что нашли» и «что видел человек» было бы
/// дороже, чем оставить эти двери открытыми.
enum DiscoveriesAvailability {
    static let isEnabled = false

    /// Тестовый шов. `nil` значит «как в проде». Тест, выставивший значение,
    /// обязан вернуть `nil` в `tearDown` — иначе он «роняет чужой класс» (см.
    /// CLAUDE.md «Ловушки, на которые уходит по часу»).
    static var isEnabledOverride: Bool?

    static var isActive: Bool { isEnabledOverride ?? isEnabled }
}
