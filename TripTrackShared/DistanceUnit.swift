import Foundation

/// В чём человеку показывать расстояние — и вся арифметика перевода, до
/// последней константы.
///
/// **Хранение и награды остаются метрическими навсегда.** `Trip.distance` —
/// метры, `Vehicle.odometerKm` — километры, XP и уровень машины считаются по
/// километрам при любой настройке. Этот тип живёт на ГРАНИЦЕ ПОКАЗА: он
/// переводит число прямо перед тем, как его напечатают, и переводит обратно
/// то, что человек ввёл руками. Конвертированное число, попавшее в награду,
/// сдвинуло бы опыт и уровень у всех задним числом, а они лежат в базе — это
/// единственная поломка версии, которую не чинит следующий релиз.
///
/// **Почему файл в `TripTrackShared`.** Это единственная папка, которую
/// компилируют ОБА таргета — приложение и расширение Live Activity. Виджет
/// обязан считать те же мили теми же числами, а App Group в проекте нет, так
/// что общий файл кода — единственный канал «одной арифметики» через границу
/// процесса. Отсюда же запрет: этот файл НЕ ЗНАЕТ ни `AppStrings`, ни
/// `LanguageManager`, ни `UserDefaults` — их в виджете не существует, и
/// первое же обращение к ним обрушит сборку расширения. Подписи собирает
/// `AppStrings.unitDistanceShort` (в приложении) и `LiveActivityStrings` (за
/// границей), текущий выбор отдаёт `DistanceUnit.current` — расширение в
/// отдельном файле таргета приложения, чтобы виджет физически не смог его
/// позвать и молча получить километры из чужого контейнера настроек.
///
/// **`rawValue` менять нельзя никогда.** Ровно эти две строки лежат в ключе
/// `UserDefaults`, в колонке `UserSettingsEntity.distanceUnit` и в поле
/// `SettingsSyncPayload.distanceUnit` — то есть это контракт и с сервером, и
/// со вторым телефоном.
enum DistanceUnit: String, CaseIterable {
    case km = "km"
    case miles = "miles"

    /// Единственное место в проекте, где живёт эта константа. Международная
    /// миля, по определению — ровно 1609.344 м, поэтому она записана точно, а
    /// не «1609» и не «1.609».
    static let metresPerMile = 1609.344

    /// Международный фут, по определению — ровно 0.3048 м.
    static let metresPerFoot = 0.3048

    /// Ключ выбора в `UserDefaults`. Совпадает с именем колонки в базе, и это
    /// не совпадение: см. про `rawValue` выше.
    static let storageKey = "distanceUnit"

    // MARK: - Расстояние

    /// Метры → то, что печатают: километры или мили.
    func distance(fromMetres metres: Double) -> Double {
        switch self {
        case .km: return metres / 1000
        case .miles: return metres / Self.metresPerMile
        }
    }

    /// То, что человек ввёл руками, → метры. Обратная половина: без неё
    /// владелец машины с мильной приборкой не может ввести свой пробег.
    func metres(fromDistance value: Double) -> Double {
        switch self {
        case .km: return value * 1000
        case .miles: return value * Self.metresPerMile
        }
    }

    // MARK: - Скорость

    /// Мили без mph не существуют: экран с «79 mi» и «68 км/ч» врёт сильнее,
    /// чем полностью метрический. Поэтому скорость идёт той же настройкой, а
    /// не второй галочкой.
    func speed(fromMetresPerSecond ms: Double) -> Double {
        switch self {
        case .km: return ms * 3.6
        case .miles: return ms * 3600 / Self.metresPerMile
        }
    }

    func metresPerSecond(fromSpeed value: Double) -> Double {
        switch self {
        case .km: return value / 3.6
        case .miles: return value * Self.metresPerMile / 3600
        }
    }

    // MARK: - Высота

    /// Метры → метры или футы. Метры возвращаются БЕЗ единого действия над
    /// ними: строгая тождественность здесь под тестом, потому что высота
    /// сегодня форматируется функцией про пробег, и любая «на всякий случай»
    /// вставленная конверсия увезла бы её в мили ×0.621.
    func elevation(fromMetres metres: Double) -> Double {
        switch self {
        case .km: return metres
        case .miles: return metres / Self.metresPerFoot
        }
    }

    // MARK: - Расход

    /// Литры на 100 км → литры на 100 миль. Сотня миль длиннее сотни
    /// километров, поэтому число РАСТЁТ: 8 л/100 км — это 12.9 л/100 миль.
    ///
    /// Это чинит живой баг, а не заводит новое: выбор миль сегодня меняет
    /// подпись на «л/100 миль», а число оставляет километровым.
    func consumptionPer100(fromPer100Km value: Double) -> Double {
        switch self {
        case .km: return value
        case .miles: return value * Self.metresPerMile / 1000
        }
    }

    func per100Km(fromConsumptionPer100 value: Double) -> Double {
        switch self {
        case .km: return value
        case .miles: return value * 1000 / Self.metresPerMile
        }
    }

    // MARK: - Точность показа

    /// Граница «десятые / целое» В ЕДИНИЦАХ ПОКАЗА: до неё число печатается с
    /// одной десятой, дальше — целым с разрядами.
    ///
    /// Шесть, а не десять: точность обязана меняться на одном и том же
    /// ФИЗИЧЕСКОМ расстоянии, а не на числе, которое случайно читается как
    /// «10». Десять километров — это 6.2 мили, поэтому у миль порог 6.
    var tenthsBelow: Double {
        self == .miles ? 6 : 10
    }

    /// Показывать ли десятые у УЖЕ переведённого числа.
    ///
    /// Правило одно на оба процесса, и живёт оно здесь по той же причине, по
    /// которой здесь живёт сама арифметика: виджет `Measure` позвать не может
    /// (тот в таргете приложения), а «до десяти — с десятыми» до 0.6.7 было
    /// независимо переписано ЧЕТЫРЕ раза — в отметках, в строке гаража и
    /// ДВАЖДЫ в самой живой активности. Пока единица была одна, четыре копии
    /// давали одинаковый ответ; на второй они разъезжаются, и «12,4 км» на
    /// экране записи встречает «7.7» на локскрине.
    func showsTenths(_ shown: Double) -> Bool {
        shown < tenthsBelow
    }

    // MARK: - Чего здесь нет

    // Площади («км² освоено») здесь нет и в 0.6.7 не будет: строки того экрана
    // мёртвые, их никто не зовёт, и заводить конверсию под несуществующий
    // показ — заводить непроверяемое число. Но если экран оживёт, коэффициент
    // квадратной мили — 0.386102, а НЕ 0.621371, и приехать он обязан сюда же,
    // а не в тот экран. Записано тут, потому что вместе с удалёнными строками
    // `km2Short`/`km2ExploredLabel` из проекта уехало и это знание.
}
